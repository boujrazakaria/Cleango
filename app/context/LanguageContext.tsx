const rtlLangs: Lang[] = ["ar"];

type LanguageContextValue = {
  lang: Lang;
  dir: Direction;
  t: Dict;
  setLang: (l: Lang) => void;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

const STORAGE_KEY = "cleango_lang";
const LANGUAGE_CHANGE_EVENT = "cleango-language-change";

function subscribeToLanguageChanges(onChange: () => void) {
  const notify = () => onChange();
  window.addEventListener("storage", notify);
  window.addEventListener(LANGUAGE_CHANGE_EVENT, notify);

  return () => {
    window.removeEventListener("storage", notify);
    window.removeEventListener(LANGUAGE_CHANGE_EVENT, notify);
  };
}

function getBrowserLanguage(): Lang {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY) as Lang | null;
    if (saved && translations[saved]) return saved;

    const browser = navigator.language.slice(0, 2) as Lang;
    return translations[browser] ? browser : "ar";
  } catch {
    return "ar";
  }
}

function setBrowserLanguage(lang: Lang) {
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Language selection still works for the current page without storage.
  }
  window.dispatchEvent(new Event(LANGUAGE_CHANGE_EVENT));
}

function getServerLanguage(): Lang {
  return "ar";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const lang = useSyncExternalStore(
    subscribeToLanguageChanges,
    getBrowserLanguage,
    getServerLanguage
  );

  // Update the document language and direction.
  useEffect(() => {
    const dir: Direction = rtlLangs.includes(lang) ? "rtl" : "ltr";
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang]);

  const setLang = (l: Lang) => setBrowserLanguage(l);

  const value = useMemo<LanguageContextValue>(() => {
    const dir: Direction = rtlLangs.includes(lang) ? "rtl" : "ltr";
    return {
      lang,
      dir,
      t: translations[lang],
      setLang,
    };
  }, [lang]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error("useLanguage must be used inside <LanguageProvider>");
  }
  return ctx;
}